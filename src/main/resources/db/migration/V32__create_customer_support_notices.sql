CREATE TABLE notices (
    notice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(20) NOT NULL,
    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    is_pinned BOOLEAN NOT NULL DEFAULT false,
    published_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT chk_notices_category CHECK (category IN ('SERVICE', 'UPDATE', 'MAINTENANCE', 'EVENT'))
);

CREATE INDEX idx_notices_published_at ON notices (published_at DESC);
CREATE INDEX idx_notices_category_published_at ON notices (category, published_at DESC);
