CREATE TABLE payment_products (
    payment_product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    billing_type VARCHAR(20) NOT NULL,
    amount BIGINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT uq_payment_products_code UNIQUE (product_code),
    CONSTRAINT chk_payment_products_code CHECK (product_code IN ('PRO_MONTHLY', 'PRO_YEARLY', 'SURVIVAL_REPORT')),
    CONSTRAINT chk_payment_products_billing_type CHECK (billing_type IN ('ONE_TIME', 'SUBSCRIPTION')),
    CONSTRAINT chk_payment_products_amount CHECK (amount > 0)
);

CREATE TABLE payment_orders (
    payment_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (user_id),
    payment_product_id BIGINT NOT NULL REFERENCES payment_products (payment_product_id),
    order_key VARCHAR(100) NOT NULL,
    report_id VARCHAR(100),
    product_name VARCHAR(100) NOT NULL,
    amount BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    provider_order_no VARCHAR(100),
    requested_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT uq_payment_orders_order_key UNIQUE (order_key),
    CONSTRAINT uq_payment_orders_provider_order_no UNIQUE (provider_order_no),
    CONSTRAINT chk_payment_orders_status CHECK (status IN ('READY', 'PAYMENT_REQUESTED', 'COMPLETED', 'CANCELED', 'FAILED', 'EXPIRED')),
    CONSTRAINT chk_payment_orders_amount CHECK (amount > 0)
);

CREATE INDEX idx_payment_orders_user_created_at ON payment_orders (user_id, created_at DESC);

CREATE TABLE payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_order_id BIGINT NOT NULL REFERENCES payment_orders (payment_order_id),
    provider VARCHAR(20) NOT NULL,
    provider_order_no VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL,
    payment_method VARCHAR(30),
    approval_no VARCHAR(100),
    receipt_url VARCHAR(1000),
    completed_at TIMESTAMPTZ,
    canceled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT uq_payments_payment_order UNIQUE (payment_order_id),
    CONSTRAINT uq_payments_provider_order_no UNIQUE (provider_order_no),
    CONSTRAINT chk_payments_provider CHECK (provider IN ('GMPAY')),
    CONSTRAINT chk_payments_status CHECK (status IN ('READY', 'COMPLETED', 'CANCELED', 'FAILED'))
);

CREATE TABLE subscriptions (
    subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (user_id),
    payment_product_id BIGINT NOT NULL REFERENCES payment_products (payment_product_id),
    status VARCHAR(20) NOT NULL,
    encrypted_billing_key VARCHAR(500),
    started_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    next_billing_at TIMESTAMPTZ,
    canceled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT chk_subscriptions_status CHECK (status IN ('PENDING', 'ACTIVE', 'PAYMENT_FAILED', 'CANCELED', 'EXPIRED'))
);

CREATE INDEX idx_subscriptions_user_status_expires_at ON subscriptions (user_id, status, expires_at DESC);

CREATE TABLE report_purchase_entitlements (
    report_purchase_entitlement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (user_id),
    report_id VARCHAR(100) NOT NULL,
    payment_order_id BIGINT NOT NULL REFERENCES payment_orders (payment_order_id),
    granted_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_report_purchase_entitlements_user_report UNIQUE (user_id, report_id),
    CONSTRAINT uq_report_purchase_entitlements_payment_order UNIQUE (payment_order_id)
);

CREATE TABLE refund_requests (
    refund_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES payments (payment_id),
    user_id BIGINT NOT NULL REFERENCES users (user_id),
    status VARCHAR(20) NOT NULL,
    reason TEXT NOT NULL,
    reviewed_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    rejection_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT uq_refund_requests_payment UNIQUE (payment_id),
    CONSTRAINT chk_refund_requests_status CHECK (status IN ('REQUESTED', 'UNDER_REVIEW', 'APPROVED', 'REJECTED', 'COMPLETED'))
);

