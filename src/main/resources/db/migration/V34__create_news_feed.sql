CREATE TABLE news_articles (
    news_article_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(40) NOT NULL,
    source_key VARCHAR(300) NOT NULL,
    content_type VARCHAR(20) NOT NULL,
    display_mode VARCHAR(20) NOT NULL,
    category VARCHAR(30) NOT NULL,
    title VARCHAR(1000) NOT NULL,
    normalized_title VARCHAR(1000) NOT NULL,
    summary TEXT,
    body TEXT,
    original_url VARCHAR(2000) NOT NULL,
    tags VARCHAR(2000) NOT NULL DEFAULT '',
    published_at TIMESTAMPTZ NOT NULL,
    view_count BIGINT NOT NULL DEFAULT 0 CHECK (view_count >= 0),
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(source, source_key),
    CHECK (category IN ('MARKET', 'COMMERCIAL', 'TRANSACTION', 'POLICY_FINANCE')),
    CHECK (
        (content_type = 'NEWS' AND display_mode = 'OUTLINK' AND summary IS NULL AND body IS NULL
            AND source IN ('MSS_PRESS', 'MSS_ANNOUNCEMENT'))
        OR (content_type = 'INSIGHT' AND display_mode = 'INTERNAL'
            AND summary IS NOT NULL AND body IS NOT NULL
            AND source IN ('SEOUL_SALES', 'REB_RENT'))
    )
);
CREATE INDEX idx_news_articles_feed ON news_articles(published_at DESC, news_article_id DESC) WHERE active;
CREATE INDEX idx_news_articles_category ON news_articles(category, published_at DESC) WHERE active;
CREATE INDEX idx_news_articles_title ON news_articles(normalized_title);

CREATE TABLE news_article_regions (
    article_id BIGINT NOT NULL REFERENCES news_articles(news_article_id) ON DELETE CASCADE,
    region_id BIGINT NOT NULL REFERENCES regions(region_id),
    PRIMARY KEY(article_id, region_id)
);
CREATE INDEX idx_news_regions_region ON news_article_regions(region_id, article_id);
CREATE TABLE news_article_industries (
    article_id BIGINT NOT NULL REFERENCES news_articles(news_article_id) ON DELETE CASCADE,
    industry_id BIGINT NOT NULL REFERENCES industries(industry_id),
    PRIMARY KEY(article_id, industry_id)
);
CREATE INDEX idx_news_industries_industry ON news_article_industries(industry_id, article_id);

-- 메타데이터만 저장한다. RSS 원문·HTML·첨부파일 payload는 보관하지 않는다.
CREATE TABLE news_ingestion_items (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(40) NOT NULL CHECK (source IN ('MSS_PRESS', 'MSS_ANNOUNCEMENT')),
    item_key VARCHAR(64) NOT NULL,
    title VARCHAR(1000),
    original_url VARCHAR(2000),
    published_text VARCHAR(100),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK(status IN ('PENDING','RETRY','PUBLISHED','SKIPPED','INVALID','FAILED')),
    attempts INT NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 4),
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    error_code VARCHAR(100),
    article_id BIGINT REFERENCES news_articles(news_article_id),
    duplicate_candidate_id BIGINT REFERENCES news_articles(news_article_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(source, item_key)
);
CREATE INDEX idx_news_ingestion_pending ON news_ingestion_items(source, next_attempt_at, item_id)
    WHERE status IN ('PENDING', 'RETRY');

CREATE TABLE news_job_leases (
    job_key VARCHAR(40) PRIMARY KEY,
    owner_token UUID NOT NULL,
    lease_until TIMESTAMPTZ NOT NULL
);
CREATE TABLE news_source_states (
    source VARCHAR(40) PRIMARY KEY,
    last_success_at TIMESTAMPTZ,
    last_failure_at TIMESTAMPTZ
);
CREATE TABLE news_view_logs (
    article_id BIGINT NOT NULL REFERENCES news_articles(news_article_id) ON DELETE CASCADE,
    viewer_hash VARCHAR(64) NOT NULL,
    view_date DATE NOT NULL,
    viewed_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY(article_id, viewer_hash, view_date)
);
CREATE INDEX idx_news_view_logs_date ON news_view_logs(view_date, article_id);
CREATE TABLE news_digests (
    digest_date DATE NOT NULL,
    article_id BIGINT NOT NULL REFERENCES news_articles(news_article_id),
    position INT NOT NULL CHECK(position BETWEEN 1 AND 12),
    PRIMARY KEY(digest_date, article_id),
    UNIQUE(digest_date, position)
);
