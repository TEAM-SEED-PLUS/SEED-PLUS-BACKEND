    tmzon_17_21_selng_amt BIGINT NOT NULL DEFAULT 0,
    tmzon_21_24_selng_amt BIGINT NOT NULL DEFAULT 0,

    ml_selng_amt BIGINT NOT NULL DEFAULT 0,
    fml_selng_amt BIGINT NOT NULL DEFAULT 0,

    agrde_10_selng_amt BIGINT NOT NULL DEFAULT 0,
    agrde_20_selng_amt BIGINT NOT NULL DEFAULT 0,
    agrde_30_selng_amt BIGINT NOT NULL DEFAULT 0,
    agrde_40_selng_amt BIGINT NOT NULL DEFAULT 0,
    agrde_50_selng_amt BIGINT NOT NULL DEFAULT 0,
    agrde_60_above_selng_amt BIGINT NOT NULL DEFAULT 0,

    mdwk_selng_co BIGINT NOT NULL DEFAULT 0,
    wkend_selng_co BIGINT NOT NULL DEFAULT 0,
