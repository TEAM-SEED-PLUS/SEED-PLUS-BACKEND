CREATE INDEX idx_commercial_estimated_sales_stdr_yyqu_cd
    ON commercial_estimated_sales(stdr_yyqu_cd);

CREATE INDEX idx_commercial_estimated_sales_trdar_cd
    ON commercial_estimated_sales(trdar_cd);

CREATE INDEX idx_commercial_estimated_sales_svc_induty_cd
    ON commercial_estimated_sales(svc_induty_cd);


CREATE TABLE commercial_data_collect_histories (
    commercial_data_collect_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_type VARCHAR(100) NOT NULL,
    target_key VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL,
    total_count BIGINT NOT NULL DEFAULT 0,
    fetched_count BIGINT NOT NULL DEFAULT 0,
    last_start_index BIGINT NOT NULL DEFAULT 0,
    error_message VARCHAR(2000),
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,

    CONSTRAINT chk_commercial_data_collect_histories_status
        CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED'))
);

CREATE UNIQUE INDEX uq_commercial_data_collect_histories_completed
    ON commercial_data_collect_histories(data_type, target_key)
    WHERE status = 'COMPLETED';

CREATE INDEX idx_commercial_data_collect_histories_data_type_target_key
    ON commercial_data_collect_histories(data_type, target_key);
