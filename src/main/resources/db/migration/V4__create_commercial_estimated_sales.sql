    trdar_cd_nm VARCHAR(150),
    svc_induty_cd VARCHAR(30) NOT NULL,
    svc_induty_cd_nm VARCHAR(100),

    thsmon_selng_amt BIGINT NOT NULL DEFAULT 0,
    thsmon_selng_co BIGINT NOT NULL DEFAULT 0,

    mdwk_selng_amt BIGINT NOT NULL DEFAULT 0,
    wkend_selng_amt BIGINT NOT NULL DEFAULT 0,
    mon_selng_amt BIGINT NOT NULL DEFAULT 0,
    tues_selng_amt BIGINT NOT NULL DEFAULT 0,
    wed_selng_amt BIGINT NOT NULL DEFAULT 0,
    thur_selng_amt BIGINT NOT NULL DEFAULT 0,
    fri_selng_amt BIGINT NOT NULL DEFAULT 0,
    sat_selng_amt BIGINT NOT NULL DEFAULT 0,
    sun_selng_amt BIGINT NOT NULL DEFAULT 0,

