    agrde_20_selng_co BIGINT NOT NULL DEFAULT 0,
    agrde_30_selng_co BIGINT NOT NULL DEFAULT 0,
    agrde_40_selng_co BIGINT NOT NULL DEFAULT 0,
    agrde_50_selng_co BIGINT NOT NULL DEFAULT 0,
    agrde_60_above_selng_co BIGINT NOT NULL DEFAULT 0,

