    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,

    CONSTRAINT uq_commercial_estimated_sales_quarter_area_industry
        UNIQUE (stdr_yyqu_cd, trdar_cd, svc_induty_cd),

    CONSTRAINT chk_commercial_estimated_sales_amounts CHECK (
        thsmon_selng_amt >= 0
        AND thsmon_selng_co >= 0
