    tues_selng_co BIGINT NOT NULL DEFAULT 0,
    wed_selng_co BIGINT NOT NULL DEFAULT 0,
    thur_selng_co BIGINT NOT NULL DEFAULT 0,
    fri_selng_co BIGINT NOT NULL DEFAULT 0,
    sat_selng_co BIGINT NOT NULL DEFAULT 0,
    sun_selng_co BIGINT NOT NULL DEFAULT 0,

    tmzon_00_06_selng_co BIGINT NOT NULL DEFAULT 0,
    tmzon_06_11_selng_co BIGINT NOT NULL DEFAULT 0,
    tmzon_11_14_selng_co BIGINT NOT NULL DEFAULT 0,
    tmzon_14_17_selng_co BIGINT NOT NULL DEFAULT 0,
    tmzon_17_21_selng_co BIGINT NOT NULL DEFAULT 0,
    tmzon_21_24_selng_co BIGINT NOT NULL DEFAULT 0,

    ml_selng_co BIGINT NOT NULL DEFAULT 0,
    fml_selng_co BIGINT NOT NULL DEFAULT 0,

