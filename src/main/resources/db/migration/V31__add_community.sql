CREATE TABLE community_posts (
    community_post_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    title VARCHAR(100) NOT NULL,
    content VARCHAR(10000) NOT NULL,
    location VARCHAR(200),
    like_count BIGINT NOT NULL DEFAULT 0,
    comment_count BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT chk_community_posts_counts CHECK (like_count >= 0 AND comment_count >= 0),
    CONSTRAINT chk_community_posts_text CHECK (length(btrim(title)) > 0 AND length(btrim(content)) > 0)
);

CREATE TABLE community_comments (
    community_comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES community_posts(community_post_id),
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    content VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT chk_community_comments_text CHECK (length(btrim(content)) > 0)
);

CREATE TABLE community_likes (
    community_like_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES community_posts(community_post_id),
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_community_likes UNIQUE (post_id, user_id)
);

CREATE TABLE community_post_regions (
    post_id BIGINT NOT NULL REFERENCES community_posts(community_post_id),
    region_id BIGINT NOT NULL REFERENCES regions(region_id),
    PRIMARY KEY (post_id, region_id)
);

CREATE TABLE community_post_industries (
    post_id BIGINT NOT NULL REFERENCES community_posts(community_post_id),
    industry_id BIGINT NOT NULL REFERENCES industries(industry_id),
    PRIMARY KEY (post_id, industry_id)
);

CREATE INDEX idx_community_posts_created ON community_posts(created_at DESC, community_post_id DESC)
    WHERE deleted_at IS NULL;
CREATE INDEX idx_community_posts_likes ON community_posts(like_count DESC, community_post_id DESC)
    WHERE deleted_at IS NULL;
CREATE INDEX idx_community_comments_post_created ON community_comments(post_id, created_at, community_comment_id)
    WHERE deleted_at IS NULL;
CREATE INDEX idx_community_likes_user_post ON community_likes(user_id, post_id);
CREATE INDEX idx_community_post_regions_region_post ON community_post_regions(region_id, post_id);
CREATE INDEX idx_community_post_industries_industry_post ON community_post_industries(industry_id, post_id);
